#!/usr/bin/env zsh

# =============================================================================
# Скрипт создания самоподписанного сертификата и проверки срока действия
# Задание 4 из Части C
# =============================================================================

set -e

# Рабочая директория
WORK_DIR="${1:-$(cd "$(dirname "$0")" && pwd)}"
cd "$WORK_DIR"

echo "=============================================="
echo "Создание самоподписанного сертификата"
echo "=============================================="
echo ""

# -----------------------------------------------------------------------------
# Шаг 1: Создание самоподписанного сертификата
# -----------------------------------------------------------------------------
echo "[Шаг 1] Создание самоподписанного сертификата..."
echo "  Срок действия: 365 дней"
echo "  Алгоритм: RSA 2048, SHA-256"
echo ""

openssl req -x509 -newkey rsa:2048 \
    -keyout cert_private.pem \
    -out cert.pem \
    -days 365 \
    -nodes \
    -subj "/C=RU/ST=Moscow/L=Moscow/O=CryptoLab/CN=localhost" 2>/dev/null

echo "  ✓ Сертификат создан: cert.pem"
echo "  ✓ Приватный ключ: cert_private.pem"
echo ""

# -----------------------------------------------------------------------------
# Шаг 2: Проверка информации о сертификате
# -----------------------------------------------------------------------------
echo "[Шаг 2] Информация о сертификате:"
echo "----------------------------------------------"
openssl x509 -in cert.pem -noout -subject -issuer
echo ""

# -----------------------------------------------------------------------------
# Шаг 3: Проверка срока действия
# -----------------------------------------------------------------------------
echo "[Шаг 3] Срок действия сертификата:"
echo "----------------------------------------------"
openssl x509 -in cert.pem -noout -dates
echo ""

# -----------------------------------------------------------------------------
# Шаг 4: Дополнительная информация
# -----------------------------------------------------------------------------
echo "[Шаг 4] Дополнительная информация:"
echo "----------------------------------------------"
openssl x509 -in cert.pem -noout -text | head -20
echo "  ... (показаны первые 20 строк)"
echo ""

# -----------------------------------------------------------------------------
# Шаг 5: Проверка истёкшего сертификата (тест)
# -----------------------------------------------------------------------------
echo "[Шаг 5] Тест: создание сертификата с коротким сроком (1 день)..."
openssl req -x509 -newkey rsa:2048 \
    -keyout expired_private.pem \
    -out expired_cert.pem \
    -days 1 \
    -nodes \
    -subj "/C=RU/ST=Moscow/L=Moscow/O=CryptoLab/CN=short_lived" 2>/dev/null

echo "  ✓ Создан тестовый сертификат: expired_cert.pem"
echo ""
echo "  Срок действия:"
openssl x509 -in expired_cert.pem -noout -dates
echo ""

# -----------------------------------------------------------------------------
# Итоги
# -----------------------------------------------------------------------------
echo "=============================================="
echo "ИТОГИ:"
echo "=============================================="
echo "  • Сертификат: cert.pem"
echo "  • Приватный ключ: cert_private.pem"
echo "  • Тестовый (истёкший): expired_cert.pem"
echo ""
echo "  Для проверки срока действия используйте:"
echo "  openssl x509 -in cert.pem -noout -dates"
echo "=============================================="
